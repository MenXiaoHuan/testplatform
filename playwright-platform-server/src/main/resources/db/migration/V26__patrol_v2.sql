-- 旧巡页过程表按产品决策直接清理。

DROP TABLE IF EXISTS patrol_assertion;
DROP TABLE IF EXISTS patrol_finding;
DROP TABLE IF EXISTS patrol_case_step;
DROP TABLE IF EXISTS patrol_case;
DROP TABLE IF EXISTS patrol_edge;
DROP TABLE IF EXISTS patrol_step;
DROP TABLE IF EXISTS patrol_page;
DROP TABLE IF EXISTS patrol_task;

CREATE TABLE ai_model_config (
    id bigint PRIMARY KEY AUTO_INCREMENT,
    space_id bigint NULL COMMENT 'NULL 表示平台默认模型',
    name varchar(128) NOT NULL,
    provider_type varchar(32) NOT NULL DEFAULT 'OPENAI_COMPATIBLE',
    base_url varchar(512) NOT NULL,
    api_key_encrypted text NOT NULL,
    model_id varchar(128) NOT NULL,
    supports_vision tinyint(1) NOT NULL DEFAULT 0,
    supports_tools tinyint(1) NOT NULL DEFAULT 0,
    supports_json tinyint(1) NOT NULL DEFAULT 1,
    max_tokens int NOT NULL DEFAULT 4096,
    temperature decimal(3,2) NOT NULL DEFAULT 0.20,
    enabled tinyint(1) NOT NULL DEFAULT 1,
    last_test_status varchar(16) NULL,
    last_test_message varchar(512) NULL,
    last_tested_at datetime NULL,
    created_by varchar(128) NULL,
    created_at datetime NOT NULL DEFAULT current_timestamp,
    updated_at datetime NOT NULL DEFAULT current_timestamp ON UPDATE current_timestamp,
    KEY idx_ai_model_space (space_id),
    UNIQUE KEY uk_ai_model_scope_name (space_id, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE patrol_scene (
    id bigint PRIMARY KEY AUTO_INCREMENT,
    space_id bigint NOT NULL,
    name varchar(128) NOT NULL,
    description varchar(512) NULL,
    start_url varchar(2048) NOT NULL,
    browser varchar(32) NOT NULL DEFAULT 'chromium',
    headless tinyint(1) NOT NULL DEFAULT 1,
    auth_type varchar(32) NOT NULL DEFAULT 'NONE',
    auth_cookie_encrypted text NULL,
    auth_token_encrypted text NULL,
    auth_token_header varchar(128) NULL,
    auth_local_storage_encrypted text NULL,
    plan_model_id bigint NULL,
    judge_model_id bigint NULL,
    task_brief varchar(1024) NULL,
    budget_duration_minutes int NOT NULL DEFAULT 15,
    budget_llm_tokens int NOT NULL DEFAULT 300000,
    budget_cases int NOT NULL DEFAULT 10,
    scroll_scan tinyint(1) NOT NULL DEFAULT 1,
    record_video tinyint(1) NOT NULL DEFAULT 1,
    auto_approve_write tinyint(1) NOT NULL DEFAULT 0,
    auto_approve_destructive tinyint(1) NOT NULL DEFAULT 0,
    schedule_enabled tinyint(1) NOT NULL DEFAULT 0,
    cron_expression varchar(64) NULL,
    next_run_at datetime NULL,
    last_run_at datetime NULL,
    last_task_id bigint NULL,
    last_task_status varchar(32) NULL,
    created_by varchar(128) NULL,
    created_at datetime NOT NULL DEFAULT current_timestamp,
    updated_at datetime NOT NULL DEFAULT current_timestamp ON UPDATE current_timestamp,
    UNIQUE KEY uk_patrol_scene_name (space_id, name),
    KEY idx_patrol_scene_schedule (schedule_enabled, next_run_at),
    KEY idx_patrol_scene_space (space_id),
    CONSTRAINT fk_patrol_scene_plan_model FOREIGN KEY (plan_model_id) REFERENCES ai_model_config(id) ON DELETE SET NULL,
    CONSTRAINT fk_patrol_scene_judge_model FOREIGN KEY (judge_model_id) REFERENCES ai_model_config(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE patrol_task (
    id bigint PRIMARY KEY AUTO_INCREMENT,
    space_id bigint NOT NULL,
    scene_id bigint NOT NULL,
    scene_name varchar(128) NOT NULL,
    trigger_type varchar(16) NOT NULL DEFAULT 'MANUAL',
    status varchar(24) NOT NULL,
    current_stage varchar(24) NOT NULL,
    start_url varchar(2048) NOT NULL,
    task_brief varchar(1024) NULL,
    scene_snapshot_json mediumtext NULL,
    model_snapshot_json mediumtext NULL,
    snapshot_json mediumtext NULL,
    snapshot_screenshot_key varchar(512) NULL,
    approval_json text NULL,
    approved_by varchar(128) NULL,
    approved_at datetime NULL,
    budget_duration_minutes int NOT NULL DEFAULT 15,
    budget_llm_tokens int NOT NULL DEFAULT 300000,
    budget_cases int NOT NULL DEFAULT 10,
    case_count int NOT NULL DEFAULT 0,
    case_pass_count int NOT NULL DEFAULT 0,
    case_fail_count int NOT NULL DEFAULT 0,
    case_skip_count int NOT NULL DEFAULT 0,
    finding_p0_count int NOT NULL DEFAULT 0,
    finding_p1_count int NOT NULL DEFAULT 0,
    finding_p2_count int NOT NULL DEFAULT 0,
    llm_token_used int NOT NULL DEFAULT 0,
    degraded tinyint(1) NOT NULL DEFAULT 0,
    result_message varchar(2048) NULL,
    cancel_requested tinyint(1) NOT NULL DEFAULT 0,
    retention_until datetime NULL,
    started_at datetime NULL,
    finished_at datetime NULL,
    duration_ms bigint NULL,
    created_by varchar(128) NULL,
    created_at datetime NOT NULL DEFAULT current_timestamp,
    updated_at datetime NOT NULL DEFAULT current_timestamp ON UPDATE current_timestamp,
    KEY idx_patrol_task_space (space_id, created_at),
    KEY idx_patrol_task_scene (scene_id, created_at),
    KEY idx_patrol_task_status (status),
    KEY idx_patrol_task_retention (retention_until),
    CONSTRAINT fk_patrol_task_scene FOREIGN KEY (scene_id) REFERENCES patrol_scene(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE patrol_case (
    id bigint PRIMARY KEY AUTO_INCREMENT,
    task_id bigint NOT NULL,
    seq int NOT NULL,
    name varchar(200) NOT NULL,
    intent varchar(1000) NULL,
    expected varchar(2000) NULL,
    priority varchar(4) NOT NULL DEFAULT 'P1',
    worst_risk varchar(16) NOT NULL DEFAULT 'READ',
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    exec_status varchar(16) NOT NULL DEFAULT 'PENDING',
    source varchar(16) NOT NULL DEFAULT 'LLM',
    judge_reason varchar(1000) NULL,
    video_key varchar(512) NULL,
    console_key varchar(512) NULL,
    dom_key varchar(512) NULL,
    screenshot_key varchar(512) NULL,
    model_id varchar(128) NULL,
    tokens int NOT NULL DEFAULT 0,
    duration_ms bigint NULL,
    degraded tinyint(1) NOT NULL DEFAULT 0,
    created_at datetime NOT NULL DEFAULT current_timestamp,
    KEY idx_patrol_case_task (task_id, seq),
    CONSTRAINT fk_patrol_case_task FOREIGN KEY (task_id) REFERENCES patrol_task(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE patrol_case_step (
    id bigint PRIMARY KEY AUTO_INCREMENT,
    case_id bigint NOT NULL,
    seq int NOT NULL,
    action varchar(32) NOT NULL,
    target_selector varchar(1000) NULL,
    locator_json text NULL,
    target_label varchar(500) NULL,
    input_value varchar(1000) NULL,
    operation varchar(16) NOT NULL DEFAULT 'READ',
    risk varchar(16) NOT NULL DEFAULT 'READ',
    approved tinyint(1) NOT NULL DEFAULT 0,
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    message varchar(1000) NULL,
    screenshot_key varchar(512) NULL,
    request_json text NULL,
    duration_ms bigint NULL,
    created_at datetime NOT NULL DEFAULT current_timestamp,
    KEY idx_patrol_case_step_case (case_id, seq),
    CONSTRAINT fk_patrol_case_step_case FOREIGN KEY (case_id) REFERENCES patrol_case(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE patrol_finding (
    id bigint PRIMARY KEY AUTO_INCREMENT,
    task_id bigint NOT NULL,
    case_id bigint NULL,
    step_seq int NULL,
    type varchar(32) NOT NULL,
    severity varchar(4) NOT NULL,
    title varchar(200) NOT NULL,
    description varchar(2000) NULL,
    evidence_json text NULL,
    status varchar(16) NOT NULL DEFAULT 'OPEN',
    degraded tinyint(1) NOT NULL DEFAULT 0,
    handled_by varchar(128) NULL,
    handled_at datetime NULL,
    created_at datetime NOT NULL DEFAULT current_timestamp,
    KEY idx_patrol_finding_task (task_id),
    KEY idx_patrol_finding_case (case_id),
    CONSTRAINT fk_patrol_finding_task FOREIGN KEY (task_id) REFERENCES patrol_task(id) ON DELETE CASCADE,
    CONSTRAINT fk_patrol_finding_case FOREIGN KEY (case_id) REFERENCES patrol_case(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
